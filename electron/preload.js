const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  startup: () => ipcRenderer.invoke('app:startup'),
  openDoc: (path) => ipcRenderer.invoke('doc:open', path),
  saveDoc: (path, text, silent, expected) => ipcRenderer.invoke('doc:save', { path, text, silent, expected }),
  savePng: (dataUrl, path) => ipcRenderer.invoke('png:save', dataUrl, path),
  printPng: (dataUrl, mode, target) => ipcRenderer.invoke('print:png', dataUrl, mode, target),
  printPages: (dataUrls, mode, target) => ipcRenderer.invoke('print:pages', dataUrls, mode, target),
  saveSvg: (svg, path) => ipcRenderer.invoke('svg:save', svg, path),
  exportZip: (entries, defaultName, path) => ipcRenderer.invoke('export:zip', entries, defaultName, path),
  showError: (message) => ipcRenderer.send('app:error', message),
  showInfo: (title, detail) => ipcRenderer.invoke('app:info', title, detail),
  openExternal: (url) => ipcRenderer.invoke('shell:open-external', url),
  log: (level, message) => ipcRenderer.send('app:log', level, message),
  confirm: (message, detail) => ipcRenderer.invoke('app:confirm', message, detail),
  setFullScreen: (on) => ipcRenderer.invoke('win:set-fullscreen', on),
  writeClipboardText: (text) => ipcRenderer.send('clipboard:write-text', text),
  writeClipboardImage: (dataUrl) => ipcRenderer.send('clipboard:write-image', dataUrl),
  writeClipboardElements: (text) => ipcRenderer.send('clipboard:write-elements', text),
  readClipboardElements: () => ipcRenderer.invoke('clipboard:read-elements'),
  readClipboardText: () => ipcRenderer.invoke('clipboard:read-text'),
  confirmDiscard: () => ipcRenderer.invoke('app:confirm-discard'),
  setDirty: (dirty) => ipcRenderer.send('doc:dirty', dirty),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  initRecovery: (key) => ipcRenderer.send('recovery:init', key),
  writeRecovery: (text, path, key, stamp) => ipcRenderer.send('recovery:write', text, path, key, stamp),
  clearRecovery: (key) => ipcRenderer.send('recovery:clear', key),
  backupNow: (text, path, docKey) => ipcRenderer.invoke('backup:now', text, path, docKey),
  listBackups: () => ipcRenderer.invoke('backup:list'),
  deleteBackup: (path) => ipcRenderer.invoke('backup:delete', path),
  restoreBackup: () => ipcRenderer.invoke('backup:restore'),
  getAssociation: () => ipcRenderer.invoke('assoc:get'),
  setAssociation: (enabled) => ipcRenderer.invoke('assoc:set', enabled),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, action, arg) => cb(action, arg)),
  onRequestSave: (cb) => ipcRenderer.on('request-save', () => cb()),
  saveResult: (ok) => ipcRenderer.send('save-result', ok),
  testNewWindow: () => ipcRenderer.invoke('test:new-window'),
  testUserData: () => ipcRenderer.invoke('test:user-data'),
  versions: {
    app: '',
    electron: process.versions.electron,
    chrome: process.versions.chrome
  }
});
