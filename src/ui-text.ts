const PATTERNS: [RegExp, string][] = [
  [/^已复制 (.+) 项$/, 'Copied $1'],
  [/^已剪切 (.+) 项$/, 'Cut $1'],
  [/^已粘贴 (.+) 项$/, 'Pasted $1'],
  [/^已替换 (.+) 处$/, 'Replaced $1'],
  [/^已导出 (.+) 页 PDF$/, 'Exported $1 pages as PDF'],
  [/^已导出 (.+) 页 (PNG|SVG)$/, 'Exported $1 pages as $2'],
  [/^已导出 (.+) 页 (PNG|SVG)…$/, 'Exporting $1 pages as $2…'],
  [/^已导出选中区域$/, 'Selection exported'],
  [/^已导出选中区域 SVG$/, 'Selection exported as SVG'],
  [/^已导出 PNG$/, 'PNG exported'],
  [/^已导出 SVG$/, 'SVG exported'],
  [/^已复制页面：(.+)$/, 'Page duplicated: $1'],
  [/^页面 (\d+)$/, 'Page $1'],
  [/^恢复测试草稿$/, 'Recovery draft'],
  [/^文字：(.*)$/, 'Text: $1'],
  [/^便签：(.*)$/, 'Sticky: $1'],
  [/^矩形：(.*)$/, 'Rectangle: $1'],
  [/^椭圆：(.*)$/, 'Ellipse: $1'],
  [/^三角形：(.*)$/, 'Triangle: $1'],
  [/^菱形：(.*)$/, 'Diamond: $1'],
  [/^五角星：(.*)$/, 'Star: $1'],
  [/^圆角矩形：(.*)$/, 'Rounded rectangle: $1'],
  [/^绘制(.+)$/, 'Draw $1']
];

export function uiText(text: string): string {
  const lang = typeof document !== 'undefined' ? document.documentElement?.lang : '';
  if (lang !== 'en') return text;
  if (ZH_EN[text]) return ZH_EN[text];
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return text;
}
